"""Infer a frozen data contract (column -> SQL type) from the base CSVs.
Writes pipeline/schemas.py. Run once; review; commit. Re-run if the source layout changes."""
import os, pprint, sys
import pandas as pd
RAW = sys.argv[1] if len(sys.argv) > 1 else "data/raw"
ID_LIKE = ("GTIN14", "SSCC18", "GLN")
out = {}
for f in sorted(os.listdir(RAW)):
    if not f.endswith(".csv"):
        continue
    df = pd.read_csv(os.path.join(RAW, f), low_memory=False)
    cols = {}
    for c in df.columns:
        s = df[c]
        if s.dropna().empty or c.endswith(ID_LIKE) or c.endswith("ID"):
            t = "text"
        elif c.endswith("TimestampUTC"):
            t = "timestamptz"
        elif c.endswith("Date") or c == "DemandMonth":
            t = "date"
        elif c.endswith(("USD", "Pct", "TempC", "Index")) and pd.api.types.is_numeric_dtype(s):
            t = "double precision"
        elif pd.api.types.is_integer_dtype(s) or (pd.api.types.is_float_dtype(s) and s.dropna().mod(1).eq(0).all() and not c.endswith(("USD", "Pct", "C", "Hours", "Index", "G", "Latitude", "Longitude"))):
            t = "bigint"
        elif pd.api.types.is_numeric_dtype(s):
            t = "double precision"
        else:
            t = "text"
        cols[c] = t
    out[f] = cols
with open("pipeline/schemas.py", "w") as fh:
    fh.write('"""AUTO-GENERATED by scripts/infer_schemas.py - frozen source data contract (CSV column -> Postgres type)."""\n\n')
    fh.write("SOURCE_SCHEMAS = " + pprint.pformat(out, width=110, sort_dicts=False) + "\n")
print({k: len(v) for k, v in out.items()})
